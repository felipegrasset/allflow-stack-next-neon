/**
 * Turns the manifests into the files the app imports (T1). Pure: path → text.
 * `scripts/modules.ts sync` writes them; `check` and the tests compare.
 *
 * Five small registries instead of one on purpose: `lib/permissions.ts` is
 * imported by `server/auth/options.ts`, so the permissions registry must not
 * pull in a module's UI or server code (it would loop back into auth); and the
 * messages registry is data only, so the i18n module may import it.
 */
import { isHandlerEntry, shimPath } from "./validate"
import { MODULE_MESSAGE_LOCALES, type ModuleManifest } from "./types"

export const GENERATED_DIR = "modules/_generated"
export const SHIM_MARKER = "// GENERATED by `pnpm modules:sync` from"

const header = (what: string) =>
  `// GENERATED by \`pnpm modules:sync\` from modules/*/manifest.json — ${what}. Do not edit.\n`

const ident = (id: string) => id.replace(/-/g, "_")
const noExt = (p: string) => p.replace(/\.(tsx?|jsx?)$/, "")

export type GeneratedModule = { manifest: ModuleManifest }

export function buildRegistryFiles(
  modules: readonly GeneratedModule[]
): Map<string, string> {
  const mods = [...modules]
    .map((m) => m.manifest)
    .sort((a, b) => a.id.localeCompare(b.id))
  const out = new Map<string, string>()

  // ── migrations ────────────────────────────────────────────────────────────
  {
    const imports: string[] = []
    const entries: string[] = []
    for (const m of mods) {
      for (const name of [...(m.migrations ?? [])].sort()) {
        const v = `m_${ident(m.id)}_${name}`
        imports.push(`import * as ${v} from "../${m.id}/db/migrations/${name}"`)
        entries.push(`  "${name}": ${v},`)
      }
    }
    out.set(
      `${GENERATED_DIR}/migrations.ts`,
      [
        header("the module migration index"),
        `import type { Migration } from "kysely/migration"`,
        ...imports,
        "",
        "/** Numbered 0100+ (the core and the genesis use 0001–0099); server/db/migrate.ts spreads this in. */",
        "export const moduleMigrations: Record<string, Migration> = {",
        ...entries,
        "}",
        "",
      ].join("\n")
    )
  }

  // ── permissions ───────────────────────────────────────────────────────────
  {
    const withPerms = mods.filter((m) => m.entrypoints?.permissions)
    const imports = withPerms.map(
      (m) =>
        `import { permissions as p_${ident(m.id)} } from "../${m.id}/${noExt(m.entrypoints!.permissions!)}"`
    )
    const stmt = withPerms.map((m) => `  ...p_${ident(m.id)}.statement,`)
    // `moduleGrant` resolves `grants[role] ?? default` to ONE type per module.
    // A plain `a ?? b` made each term a union, and the spread of N of them is
    // 2^N combinations: tsc gives up (TS2590) past ~16 modules with permissions.
    const role = (r: "owner" | "admin" | "member") =>
      withPerms.map((m) => {
        const v = ident(m.id)
        return r === "member"
          ? `    ...moduleGrant(p_${v}, "member", {} as const),`
          : `    ...moduleGrant(p_${v}, "${r}", p_${v}.statement),`
      })
    out.set(
      `${GENERATED_DIR}/permissions.ts`,
      [
        header("module RBAC statements and grants"),
        withPerms.length
          ? `import { moduleGrant } from "../contract/access"\nimport type { AdminAccessOf, CheckAdminAccess, ModulePermissions, ModuleStatement } from "../contract/types"`
          : `import type { ModuleStatement } from "../contract/types"`,
        ...imports,
        "",
        "/** Merged into `statement` by lib/permissions.ts. */",
        "export const moduleStatements = {",
        ...stmt,
        "} as const",
        "",
        "/** Merged into each built-in role by lib/permissions.ts. owner/admin default to everything a module declares. */",
        "export const moduleGrants = {",
        "  owner: {",
        ...role("owner"),
        "  },",
        "  admin: {",
        ...role("admin"),
        "  },",
        "  member: {",
        ...role("member"),
        "  },",
        "} as const",
        "",
        "/**",
        " * Who may enter /admin besides owner/admin: anyone holding ANY one",
        " * `resource:action` of a module's `adminAccess` (app/(app)/admin/layout.tsx).",
        " */",
        "export const moduleAdminAccess: { module: string; permissions: ModuleStatement }[] = [",
        ...withPerms.map(
          (m) =>
            `  { module: "${m.id}", permissions: (p_${ident(m.id)} as ModulePermissions).adminAccess ?? {} },`
        ),
        "].filter((a) => Object.keys(a.permissions).length > 0)",
        "",
        ...(withPerms.length
          ? [
              "/** Type-only: `tsc` fails if an `adminAccess` names a resource or action its module does not declare. */",
              "export type _AdminAccessChecks = [",
              ...withPerms.map(
                (m) =>
                  `  CheckAdminAccess<typeof p_${ident(m.id)}.statement, AdminAccessOf<typeof p_${ident(m.id)}>>,`
              ),
              "]",
              "",
            ]
          : []),
      ].join("\n")
    )
  }

  // ── nav + header slots ────────────────────────────────────────────────────
  {
    const navMods = mods.filter((m) => m.entrypoints?.nav)
    const headMods = mods.filter((m) => m.entrypoints?.header)
    out.set(
      `${GENERATED_DIR}/nav.ts`,
      [
        header("module navigation and header slots"),
        `import type { ModuleHeaderSlot, ModuleNavItem } from "../contract/types"`,
        ...navMods.map(
          (m) =>
            `import { nav as nav_${ident(m.id)} } from "../${m.id}/${noExt(m.entrypoints!.nav!)}"`
        ),
        ...headMods.map(
          (m) =>
            `import header_${ident(m.id)} from "../${m.id}/${noExt(m.entrypoints!.header!)}"`
        ),
        "",
        "export const moduleNavItems: ModuleNavItem[] = [",
        ...navMods.map((m) => `  ...nav_${ident(m.id)},`),
        "]",
        "",
        "export const moduleHeaderSlots: { id: string; Slot: ModuleHeaderSlot }[] = [",
        ...headMods.map(
          (m) => `  { id: "${m.id}", Slot: header_${ident(m.id)} },`
        ),
        "]",
        "",
      ].join("\n")
    )
  }

  // ── seeds ─────────────────────────────────────────────────────────────────
  {
    const seedMods = mods.filter((m) => m.entrypoints?.seed)
    out.set(
      `${GENERATED_DIR}/seeds.ts`,
      [
        header("module seeds"),
        `import type { ModuleSeed } from "../contract/types"`,
        ...seedMods.map(
          (m) =>
            `import { seed as seed_${ident(m.id)} } from "../${m.id}/${noExt(m.entrypoints!.seed!)}"`
        ),
        "",
        "/** Idempotent; server/db/seed.ts runs them after the core seed. */",
        "export const moduleSeeds: { id: string; seed: ModuleSeed }[] = [",
        ...seedMods.map(
          (m) => `  { id: "${m.id}", seed: seed_${ident(m.id)} },`
        ),
        "]",
        "",
      ].join("\n")
    )
  }

  // ── messages (i18n catalogs) ──────────────────────────────────────────────
  {
    const msgMods = mods.filter((m) => m.entrypoints?.messages)
    const checked = (m: ModuleManifest) => `msg_${ident(m.id)}`
    out.set(
      `${GENERATED_DIR}/messages.ts`,
      [
        header("module message catalogs (i18n)"),
        msgMods.length
          ? `import type { MessageTree, ModuleLocale, ModuleMessagesFile } from "../contract/types"`
          : `import type { MessageTree, ModuleLocale } from "../contract/types"`,
        ...msgMods.map(
          (m) =>
            `import * as raw_${ident(m.id)} from "../${m.id}/${noExt(m.entrypoints!.messages!)}"`
        ),
        "",
        ...(msgMods.length
          ? [
              "// Each catalog against the contract: its only top-level key is the module id, and every locale has the keys of es.",
              ...msgMods.map(
                (m) =>
                  `const ${checked(m)}: ModuleMessagesFile<"${m.id}", typeof raw_${ident(m.id)}.es> = raw_${ident(m.id)}`
              ),
              "",
            ]
          : []),
        "/** Read by modules/i18n/request.ts, which lays the core catalog over it (the core wins a clash). */",
        "export const moduleMessages: Record<ModuleLocale, MessageTree> = {",
        ...MODULE_MESSAGE_LOCALES.map(
          (l) =>
            `  ${l}: {${msgMods.length ? ` ${msgMods.map((m) => `...${checked(m)}.${l}`).join(", ")} ` : ""}},`
        ),
        "}",
        "",
      ].join("\n")
    )
  }

  // ── route shims (the only files a module puts under app/) ─────────────────
  for (const m of mods) {
    for (const r of m.routes ?? []) {
      // A page re-exports its default; a route handler re-exports its HTTP verbs.
      const reExport = isHandlerEntry(r.entry)
        ? "export *"
        : "export { default }"
      out.set(
        shimPath(r),
        `${SHIM_MARKER} modules/${m.id}/manifest.json. Do not edit.\n${reExport} from "@/modules/${m.id}/${noExt(r.entry)}"\n`
      )
    }
  }
  return out
}

// ── .env.example: the env block of the installed modules ────────────────────

export const ENV_EXAMPLE_FILE = ".env.example"
export const ENV_BLOCK_START = "# --- módulos (generado por modules:sync) ---"
export const ENV_BLOCK_END = "# --- fin módulos (generado por modules:sync) ---"

/** Wraps a description into `# ` comment lines of at most ~`width` characters. */
function commentLines(text: string, width = 78): string[] {
  const out: string[] = []
  for (const para of text.split(/\r?\n/)) {
    let line = ""
    for (const word of para.split(/\s+/).filter(Boolean)) {
      if (line && line.length + 1 + word.length > width - 2) {
        out.push(`# ${line}`)
        line = word
      } else line = line ? `${line} ${word}` : word
    }
    out.push(line ? `# ${line}` : "#")
  }
  return out
}

/** The generated block (markers included), or "" when no installed module declares `env`. */
export function buildEnvBlock(manifests: readonly ModuleManifest[]): string {
  const mods = [...manifests]
    .filter((m) => (m.env ?? []).length > 0)
    .sort((a, b) => a.id.localeCompare(b.id))
  if (!mods.length) return ""
  const seen = new Map<string, string>()
  const lines = [
    ENV_BLOCK_START,
    "# No edites este bloque: `pnpm modules:sync` lo reescribe con las `env` de",
    "# modules/*/manifest.json. Copia a .env.local las que uses y quítales el #.",
  ]
  for (const m of mods) {
    lines.push("#", `# ── ${m.id} ──`)
    for (const v of m.env ?? []) {
      const first = seen.get(v.key)
      if (first) {
        lines.push(`# ${v.key}: la misma de ${first}, más arriba.`)
        continue
      }
      seen.set(v.key, m.id)
      lines.push(...commentLines(v.description), `# ${v.key}=${v.example ?? ""}`)
    }
  }
  lines.push(ENV_BLOCK_END)
  return lines.join("\n")
}

/**
 * `current` (the text of .env.example) with the module block replaced, added
 * at the end, or removed when no module declares `env`. Nothing outside the
 * markers changes, and applying it twice gives the same text (idempotent).
 * A start marker without its end marker is replaced up to the end of the file.
 */
export function buildEnvExample(
  current: string,
  manifests: readonly ModuleManifest[]
): string {
  const block = buildEnvBlock(manifests)
  const start = current.indexOf(ENV_BLOCK_START)
  let before = current
  let after = ""
  if (start >= 0) {
    const endAt = current.indexOf(ENV_BLOCK_END, start)
    before = current.slice(0, start)
    after =
      endAt >= 0
        ? current.slice(endAt + ENV_BLOCK_END.length).replace(/^\r?\n/, "")
        : ""
  }
  if (!block) {
    if (start < 0) return current
    const joined = before.replace(/\n+$/, "\n") + after
    return joined.replace(/\n+$/, "\n")
  }
  if (start >= 0) return `${before}${block}\n${after}`
  const base = current.replace(/\n*$/, "")
  return base ? `${base}\n\n${block}\n` : `${block}\n`
}
