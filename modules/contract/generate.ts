/**
 * Turns the manifests into the files the app imports (T1). Pure: path → text.
 * `scripts/modules.ts sync` writes them; `check` and the tests compare.
 *
 * Four small registries instead of one on purpose: `lib/permissions.ts` is
 * imported by `server/auth/options.ts`, so the permissions registry must not
 * pull in a module's UI or server code (it would loop back into auth).
 */
import { isHandlerEntry, shimPath } from "./validate"
import type { ModuleManifest } from "./types"

export const GENERATED_DIR = "modules/_generated"
export const SHIM_MARKER = "// GENERATED by `pnpm modules:sync` from"

const header = (what: string) =>
  `// GENERATED by \`pnpm modules:sync\` from modules/*/manifest.json — ${what}. Do not edit.\n`

const ident = (id: string) => id.replace(/-/g, "_")
const noExt = (p: string) => p.replace(/\.(tsx?|jsx?)$/, "")

export type GeneratedModule = { manifest: ModuleManifest }

export function buildRegistryFiles(
  modules: readonly GeneratedModule[]
): Map<string, string> {
  const mods = [...modules]
    .map((m) => m.manifest)
    .sort((a, b) => a.id.localeCompare(b.id))
  const out = new Map<string, string>()

  // ── migrations ────────────────────────────────────────────────────────────
  {
    const imports: string[] = []
    const entries: string[] = []
    for (const m of mods) {
      for (const name of [...(m.migrations ?? [])].sort()) {
        const v = `m_${ident(m.id)}_${name}`
        imports.push(`import * as ${v} from "../${m.id}/db/migrations/${name}"`)
        entries.push(`  "${name}": ${v},`)
      }
    }
    out.set(
      `${GENERATED_DIR}/migrations.ts`,
      [
        header("the module migration index"),
        `import type { Migration } from "kysely/migration"`,
        ...imports,
        "",
        "/** Numbered 0100+ (the core and the genesis use 0001–0099); server/db/migrate.ts spreads this in. */",
        "export const moduleMigrations: Record<string, Migration> = {",
        ...entries,
        "}",
        "",
      ].join("\n")
    )
  }

  // ── permissions ───────────────────────────────────────────────────────────
  {
    const withPerms = mods.filter((m) => m.entrypoints?.permissions)
    const imports = withPerms.map(
      (m) =>
        `import { permissions as p_${ident(m.id)} } from "../${m.id}/${noExt(m.entrypoints!.permissions!)}"`
    )
    const stmt = withPerms.map((m) => `  ...p_${ident(m.id)}.statement,`)
    // `grants` is read through ModulePermissions so a module that declares only
    // some roles (an `as const` literal) still type-checks for the others.
    const role = (r: "owner" | "admin" | "member") =>
      withPerms.map((m) => {
        const v = ident(m.id)
        const g = `(p_${v} as ModulePermissions).grants?.${r}`
        return r === "member"
          ? `    ...(${g} ?? {}),`
          : `    ...(${g} ?? p_${v}.statement),`
      })
    out.set(
      `${GENERATED_DIR}/permissions.ts`,
      [
        header("module RBAC statements and grants"),
        ...(withPerms.length
          ? [`import type { ModulePermissions } from "../contract/types"`]
          : []),
        ...imports,
        "",
        "/** Merged into `statement` by lib/permissions.ts. */",
        "export const moduleStatements = {",
        ...stmt,
        "} as const",
        "",
        "/** Merged into each built-in role by lib/permissions.ts. owner/admin default to everything a module declares. */",
        "export const moduleGrants = {",
        "  owner: {",
        ...role("owner"),
        "  },",
        "  admin: {",
        ...role("admin"),
        "  },",
        "  member: {",
        ...role("member"),
        "  },",
        "} as const",
        "",
      ].join("\n")
    )
  }

  // ── nav + header slots ────────────────────────────────────────────────────
  {
    const navMods = mods.filter((m) => m.entrypoints?.nav)
    const headMods = mods.filter((m) => m.entrypoints?.header)
    out.set(
      `${GENERATED_DIR}/nav.ts`,
      [
        header("module navigation and header slots"),
        `import type { ModuleHeaderSlot, ModuleNavItem } from "../contract/types"`,
        ...navMods.map(
          (m) =>
            `import { nav as nav_${ident(m.id)} } from "../${m.id}/${noExt(m.entrypoints!.nav!)}"`
        ),
        ...headMods.map(
          (m) =>
            `import header_${ident(m.id)} from "../${m.id}/${noExt(m.entrypoints!.header!)}"`
        ),
        "",
        "export const moduleNavItems: ModuleNavItem[] = [",
        ...navMods.map((m) => `  ...nav_${ident(m.id)},`),
        "]",
        "",
        "export const moduleHeaderSlots: { id: string; Slot: ModuleHeaderSlot }[] = [",
        ...headMods.map(
          (m) => `  { id: "${m.id}", Slot: header_${ident(m.id)} },`
        ),
        "]",
        "",
      ].join("\n")
    )
  }

  // ── seeds ─────────────────────────────────────────────────────────────────
  {
    const seedMods = mods.filter((m) => m.entrypoints?.seed)
    out.set(
      `${GENERATED_DIR}/seeds.ts`,
      [
        header("module seeds"),
        `import type { ModuleSeed } from "../contract/types"`,
        ...seedMods.map(
          (m) =>
            `import { seed as seed_${ident(m.id)} } from "../${m.id}/${noExt(m.entrypoints!.seed!)}"`
        ),
        "",
        "/** Idempotent; server/db/seed.ts runs them after the core seed. */",
        "export const moduleSeeds: { id: string; seed: ModuleSeed }[] = [",
        ...seedMods.map(
          (m) => `  { id: "${m.id}", seed: seed_${ident(m.id)} },`
        ),
        "]",
        "",
      ].join("\n")
    )
  }

  // ── route shims (the only files a module puts under app/) ─────────────────
  for (const m of mods) {
    for (const r of m.routes ?? []) {
      // A page re-exports its default; a route handler re-exports its HTTP verbs.
      const reExport = isHandlerEntry(r.entry)
        ? "export *"
        : "export { default }"
      out.set(
        shimPath(r),
        `${SHIM_MARKER} modules/${m.id}/manifest.json. Do not edit.\n${reExport} from "@/modules/${m.id}/${noExt(r.entry)}"\n`
      )
    }
  }
  return out
}
